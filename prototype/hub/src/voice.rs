//! Windows-only local speech adapter. No microphone is opened by the server.
//! The browser explicitly captures a bounded recording and submits canonical PCM WAV.
use axum::{body::Bytes, extract::State, http::HeaderMap, routing::{get, post}, Json, Router};
use serde_json::{json, Value};
use std::{path::PathBuf, sync::LazyLock, time::Duration};
use tokio::{io::AsyncWriteExt, process::Command, sync::Semaphore};
use crate::app::{authorize, ApiError, AppState};

static RECOGNITION: LazyLock<Semaphore> = LazyLock::new(|| Semaphore::new(1));

pub fn router() -> Router<AppState> {
    Router::new()
        .route("/voice/capabilities", get(capabilities))
        .route("/voice/transcribe", post(transcribe))
}

fn script_root() -> PathBuf {
    std::env::var_os("EDITH_VOICE_DIR").map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../voice"))
}

fn powershell() -> PathBuf {
    PathBuf::from(std::env::var_os("SystemRoot").unwrap_or_else(|| "C:\\Windows".into()))
        .join("System32/WindowsPowerShell/v1.0/powershell.exe")
}

async fn invoke(script: &str, audio: Option<&[u8]>) -> Result<Value, ApiError> {
    if !cfg!(windows) {
        return Err(ApiError::unavailable("This speech adapter requires Windows. Typed input is available."));
    }
    let mut command = Command::new(powershell());
    command.args(["-NoProfile", "-NonInteractive", "-File"])
        .arg(script_root().join(script)).kill_on_drop(true)
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped());
    #[cfg(windows)]
    command.creation_flags(0x08000000); // CREATE_NO_WINDOW: no terminal interrupts the user.
    let execution = async {
        let mut child = command.spawn()?;
        if let Some(mut input) = child.stdin.take() {
            if let Some(bytes) = audio { input.write_all(bytes).await?; }
        }
        child.wait_with_output().await
    };
    let output = tokio::time::timeout(Duration::from_secs(22), execution).await
        .map_err(|_| ApiError::unavailable("Local recognition timed out. Please type or try a shorter recording."))?
        .map_err(|_| ApiError::unavailable("Could not start the local Windows speech engine."))?;
    if !output.status.success() {
        return Err(ApiError::unavailable("Local recognition failed. Please type or try again."));
    }
    serde_json::from_slice(&output.stdout)
        .map_err(|_| ApiError::unavailable("The local speech engine returned an unreadable response."))
}

async fn capabilities(State(state): State<AppState>, headers: HeaderMap) -> Result<Json<Value>, ApiError> {
    authorize(&state, &headers).await?;
    match invoke("capabilities.ps1", None).await {
        Ok(value) => Ok(Json(value)),
        Err(_) => Ok(Json(json!({"available":false,"engine":"Windows System.Speech (local)","languages":[],"detail":"Local recognition unavailable; typed input remains available."}))),
    }
}

/// Accept only the exact bounded format generated by our recorder, not arbitrary media.
fn validate_wav(bytes: &[u8]) -> Result<(), &'static str> {
    if bytes.len() < 46 || bytes.len() > 384_044 { return Err("Recording must contain between one sample and 12 seconds of audio."); }
    if &bytes[0..4] != b"RIFF" || &bytes[8..12] != b"WAVE" || &bytes[12..16] != b"fmt " || &bytes[36..40] != b"data" {
        return Err("Use a canonical 16 kHz mono PCM WAV recording.");
    }
    let u16_at = |i| u16::from_le_bytes([bytes[i], bytes[i+1]]);
    let u32_at = |i| u32::from_le_bytes([bytes[i], bytes[i+1], bytes[i+2], bytes[i+3]]);
    if u32_at(4) as usize != bytes.len()-8 || u32_at(16)!=16 || u16_at(20)!=1 || u16_at(22)!=1
        || u32_at(24)!=16_000 || u32_at(28)!=32_000 || u16_at(32)!=2 || u16_at(34)!=16
        || u32_at(40) as usize != bytes.len()-44 || (bytes.len()-44)%2!=0 {
        return Err("Recording must be 16 kHz, mono, 16-bit PCM with a valid length.");
    }
    Ok(())
}

async fn transcribe(State(state): State<AppState>, headers: HeaderMap, body: Bytes) -> Result<Json<Value>, ApiError> {
    authorize(&state, &headers).await?;
    if headers.get("content-type").and_then(|h|h.to_str().ok()).map(|v|v.split(';').next().unwrap_or("").trim()) != Some("audio/wav") {
        return Err(ApiError::bad_request("Send the recording as audio/wav."));
    }
    validate_wav(&body).map_err(ApiError::bad_request)?;
    let _permit = RECOGNITION.try_acquire().map_err(|_|ApiError::unavailable("Another recording is being processed. Please try again shortly."))?;
    // Bounded audio travels only through a child-process pipe and memory stream.
    // It never enters persistent household state, logs, or a temporary recording file.
    let value = invoke("transcribe.ps1",Some(&body)).await?;
    if value.get("text").and_then(Value::as_str).unwrap_or("").trim().is_empty() {
        return Err(ApiError::bad_request("I could not hear clear words. Please try a short phrase or type instead."));
    }
    Ok(Json(value))
}

#[cfg(test)]
mod tests {
    use super::*;
    fn wave() -> Vec<u8> {
        let mut b=Vec::new(); b.extend(b"RIFF"); b.extend(38u32.to_le_bytes()); b.extend(b"WAVEfmt ");
        b.extend(16u32.to_le_bytes()); b.extend(1u16.to_le_bytes()); b.extend(1u16.to_le_bytes());
        b.extend(16000u32.to_le_bytes()); b.extend(32000u32.to_le_bytes()); b.extend(2u16.to_le_bytes());
        b.extend(16u16.to_le_bytes()); b.extend(b"data"); b.extend(2u32.to_le_bytes()); b.extend([0,0]); b
    }
    #[test] fn valid_canonical_sample_is_accepted(){ assert!(validate_wav(&wave()).is_ok()); }
    #[test] fn bad_length_is_rejected(){ let mut b=wave(); b[40]=255; assert!(validate_wav(&b).is_err()); }
    #[test] fn stereo_is_rejected(){ let mut b=wave(); b[22]=2; assert!(validate_wav(&b).is_err()); }
    #[test] fn oversized_recording_is_rejected(){ assert!(validate_wav(&vec![0;384045]).is_err()); }
    #[test] fn unknown_container_is_rejected(){ let mut b=wave(); b[0]=0; assert!(validate_wav(&b).is_err()); }
}
